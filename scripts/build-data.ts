/**
 * Every searchable record, flattened into the packed-reference space.
 *
 * `kind` is the low-order pair of bits and the array index is everything above
 * the language bit, so a reference is one small integer rather than an object:
 * 4402 object literals in the module graph would dominate the generated file
 * and allocate on every module evaluation.
 *
 *   ref = (index << 3) | (kind << 1) | lang
 *
 *   lang   bit 0        0 = fr, 1 = ar
 *   kind   bits 1..2    0 = wilaya, 1 = daira, 2 = commune
 *   index  bits 3..     position in WILAYAS / DAIRAS / COMMUNES
 *
 * The language bit is NOT in the session spec, which packs only `kind`. It is
 * required: `SEARCH_KEYS` is one flat sorted array mixing the `fr` and `ar`
 * layers, so without it there is no way to answer `SearchResult.matched` or to
 * honour `opts.lang` without a third parallel array. `1541 << 3` is 12328, so
 * every reference stays a small integer.
 */
const SEARCH_KIND_WILAYA = 0;
const SEARCH_KIND_DAIRA = 1;
const SEARCH_KIND_COMMUNE = 2;
const SEARCH_LANG_FR = 0;
const SEARCH_LANG_AR = 1;

function packSearchRef(index: number, kind: number, lang: number): number {
  return (index << 3) | (kind << 1) | lang;
}

interface SearchEntry {
  readonly key: string;
  readonly ref: number;
}

/**
 * Builds the sorted key/ref pair list.
 *
 * Two layers only — `fr` and `ar`, 2201 records each, 4402 keys. There is
 * deliberately NO `en` layer: `name.en` differs from `name.fr` for exactly one
 * record in the whole dataset (wilaya 16, `Alger` / `Algiers`), so a third full
 * layer would add 2201 keys — roughly a third of the index's bytes — to serve a
 * single record. `lang: "en"` searches the `fr` keys plus `EN_OVERRIDES`
 * instead, which is a real bundle saving and no public-API change.
 */
function collectSearchEntries(model: Model): SearchEntry[] {
  const entries: SearchEntry[] = [];

  const add = (name: LocalizedName, index: number, kind: number): void => {
    entries.push({ key: normalize(name.fr), ref: packSearchRef(index, kind, SEARCH_LANG_FR) });
    entries.push({ key: normalize(name.ar), ref: packSearchRef(index, kind, SEARCH_LANG_AR) });
  };

  model.wilayas.forEach((wilaya, index) => add(wilaya.name, index, SEARCH_KIND_WILAYA));
  model.dairas.forEach((daira, index) => add(daira.name, index, SEARCH_KIND_DAIRA));
  model.communes.forEach((commune, index) => add(commune.name, index, SEARCH_KIND_COMMUNE));

  // Sorted at BUILD time, which is itself the optimization: a .sort() over 4402
  // strings on the first search would cost more than every query the process
  // will ever run. The sort order IS the prefix index — no trie is shipped or
  // built, only two binary searches over this array at run time.
  //
  // The tie-break on `ref` is not cosmetic. `Array.prototype.sort` is only
  // guaranteed stable within one engine version, and 1344 of these keys are
  // duplicates (4402 keys, 3058 distinct). Without the tie-break the emitted
  // bytes could differ between Node versions, which would break the
  // byte-identity discipline every other emitter in this file holds to.
  //
  // Comparison is by UTF-16 code unit, exactly what `<` does — and exactly what
  // the runtime binary search in search.ts must use. The two orderings have to
  // agree or every prefix lookup silently misses.
  entries.sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : a.ref - b.ref));
  return entries;
}

/**
 * The English exonym table: records where `name.en !== name.fr`.
 *
 * Exactly one entry today — wilaya 16, `Algiers`. Assertion 18 already proves
 * `data/raw/en-overrides.json` and the emitted wilaya name agree, so this is a
 * projection of already-gated data rather than a second source of truth.
 */
function collectEnOverrides(model: Model): SearchEntry[] {
  const entries: SearchEntry[] = [];
  model.wilayas.forEach((wilaya, index) => {
    if (wilaya.name.en !== wilaya.name.fr) {
      entries.push({
        key: normalize(wilaya.name.en),
        ref: packSearchRef(index, SEARCH_KIND_WILAYA, SEARCH_LANG_FR),
      });
    }
  });
  model.dairas.forEach((daira, index) => {
    if (daira.name.en !== daira.name.fr) {
      entries.push({
        key: normalize(daira.name.en),
        ref: packSearchRef(index, SEARCH_KIND_DAIRA, SEARCH_LANG_FR),
      });
    }
  });
  model.communes.forEach((commune, index) => {
    if (commune.name.en !== commune.name.fr) {
      entries.push({
        key: normalize(commune.name.en),
        ref: packSearchRef(index, SEARCH_KIND_COMMUNE, SEARCH_LANG_FR),
      });
    }
  });
  entries.sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : a.ref - b.ref));
  return entries;
}

function emitSearchKeys(model: Model): string {
  const entries = collectSearchEntries(model);
  const overrides = collectEnOverrides(model);

  // One key per line: a renamed commune is then exactly one changed line in
  // review, the same property the record emitters are built around. The refs
  // are opaque derived integers that no human reads record-by-record, so they
  // are packed 16 to a row to keep the file from doubling in length.
  const keyRows = entries.map((entry) => `  ${tsString(entry.key)},`);
  const refRows = chunk(
    entries.map((entry) => String(entry.ref)),
    16,
  ).map((row) => `  ${row.join(", ")},`);
  const overrideRows = overrides.map(
    (entry) => `  [${tsString(entry.key)}, ${String(entry.ref)}],`,
  );

  return [
    BANNER,
    "//",
    "// The normalized multilingual search index. Keys come from the SAME",
    "// packages/js/src/normalize.ts that search.ts calls at run time — imported,",
    "// never re-implemented here. If the two ever drift, every lookup misses",
    "// silently; tests/normalize.test.ts re-derives this whole array from the",
    "// records and compares it byte for byte, which is the only thing that",
    "// catches that.",
    "//",
    "// v1 called .toLowerCase() on 1541 corpus strings PER QUERY. This file is",
    "// why v2 normalizes exactly one string per call: the query.",
    "",
    "/**",
    " * Normalized search keys, sorted ascending by UTF-16 code unit.",
    " *",
    " * 2201 records x 2 language layers (fr, ar) = 4402 keys. There is no `en`",
    " * layer: `name.en` differs from `name.fr` for exactly one record in the",
    ' * dataset, so `lang: "en"` searches these keys plus `EN_OVERRIDES`.',
    " *",
    " * The sort order IS the prefix index. Two binary searches over this array",
    " * answer a prefix query; no trie is shipped or built.",
    " */",
    "export const SEARCH_KEYS: readonly string[] = [",
    ...keyRows,
    "];",
    "",
    "/**",
    " * Packed record reference for each key, parallel to `SEARCH_KEYS`.",
    " *",
    " *   ref = (index << 3) | (kind << 1) | lang",
    " *   lang  bit 0     0 = fr, 1 = ar",
    " *   kind  bits 1..2 0 = wilaya, 1 = daira, 2 = commune",
    " *   index bits 3..  position in WILAYAS / DAIRAS / COMMUNES",
    " *",
    " * Packed integers rather than objects: 4402 object literals would dominate",
    " * this file's bytes and allocate on every module evaluation.",
    " */",
    "export const SEARCH_REFS: readonly number[] = [",
    ...refRows,
    "];",
    "",
    "/**",
    " * `name.en` keys for the records where `en` differs from `fr`.",
    " *",
    " * Exactly one entry: wilaya 16, `Alger` / `Algiers`. This one-row table is",
    " * what makes the missing `en` key layer invisible to callers.",
    " */",
    "export const EN_OVERRIDES: readonly (readonly [key: string, ref: number])[] = [",
    ...overrideRows,
    "];",
    "",
  ].join("\n");
}

function emitTypeScriptOutputs(model: Model): Output[] {
  return [
    { kind: "text", relPath: `${GENERATED_DIR_REL}/codes.ts`, content: emitCodes(model) },
    { kind: "text", relPath: `${GENERATED_DIR_REL}/meta.ts`, content: emitMeta(model) },
    { kind: "text", relPath: `${GENERATED_DIR_REL}/wilayas.ts`, content: emitWilayas(model) },
    { kind: "text", relPath: `${GENERATED_DIR_REL}/dairas.ts`, content: emitDairas(model) },
    { kind: "text", relPath: `${GENERATED_DIR_REL}/communes.ts`, content: emitCommunes(model) },
    {
      kind: "text",
      relPath: `${GENERATED_DIR_REL}/search-keys.ts`,
      content: emitSearchKeys(model),
    },
  ];
}

/* =========================================================================== *
 * Entry point
 * =========================================================================== */

function main(): void {
  const checkOnly = process.argv.slice(2).includes("--check");
  const failures: Failures = [];

  // Phase 1
  const source = readSource(failures);
  const overrides = readOverrides(failures);

  // Phase 5 — the model has to exist before the gate: assertions 5, 17, 18 and
  // 19 are checks on the ids it mints.
  const model = buildModel(source, overrides, failures);

  // Phase 2
  assertIntegrity(source, model, failures);

  if (failures.length > 0) {
    for (const failure of failures) console.error(failure);
    console.error(`build-data: ${failures.length} check(s) failed — nothing was written`);
    // process.exitCode, not process.exit(): console.error to a pipe is async on
    // POSIX, so exiting here can truncate the very report we took care to
    // accumulate (e.g. `pnpm build:data 2>&1 | tee build.log` in CI).
    process.exitCode = 1;
    return;
  }

  // Phases 3 and 6
  const outputs = [...projectJsonOutputs(source), ...emitTypeScriptOutputs(model)];

  // Phase 4
  if (checkOnly) {
    const differing = checkOutputs(outputs);
    if (differing.length > 0) {
      console.error(
        `build-data --check: ${differing.length} of ${outputs.length} outputs are out of date ` +
          `— run \`pnpm build:data\``,
      );
      for (const relPath of differing) console.error(relPath);
      process.exitCode = 1;
      return;
    }
  } else {
    writeOutputs(outputs);
  }

  const withPostalCode = model.communes.filter((commune) => commune.postalCode !== null).length;
  console.log(
    `build-data: ${model.wilayas.length} wilayas, ${model.dairas.length} dairas, ` +
      `${model.communes.length} communes, ${withPostalCode} postal codes, ` +
      `${model.communes.length - withPostalCode} missing — all checks pass`,
  );
}

