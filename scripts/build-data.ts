/* =========================================================================== *
 * Phase 7 — the Loi 26-06 reform table
 *
 * `data/raw/reform.json` is the maintainer's transcription of the law: which of
 * the 58 wilayas mères each of the 11 new wilayas "59".."69" was carved out of.
 * It is READ ONLY. This script never writes it and must never be made to — a
 * generator able to rewrite it could overwrite a reading of the Journal Officiel
 * with its own guess, and nobody would see the difference in review.
 *
 * Two channels, and the split between them is the whole point of this phase:
 *
 *   R1..R5  HARD. Accumulated into `failures` exactly like phases 2 and 5, so a
 *           wrong transcription cannot ship.
 *   W1, W2  WARNINGS. Printed and forgotten. They are heuristics over data that
 *           is known to disagree with them, so they inform a maintainer and
 *           never gate a build.
 * =========================================================================== */

interface ReformEntry {
  readonly code: string;
  readonly nom_fr: string;
  readonly parentCode: string | null;
  readonly source: string | null;
  readonly confidence: string;
}

interface Reform {
  readonly law: string;
  readonly journalOfficiel: string;
  readonly publishedOn: string;
  readonly transitionDeadline: string;
  readonly operationalFrom: string;
  readonly previousWilayaCount: number;
  readonly currentWilayaCount: number;
  readonly newWilayas: readonly ReformEntry[];
}

/**
 * A second accumulator, parallel to `Failures` and deliberately unrelated to it.
 *
 * Warnings are printed and NEVER touch `process.exitCode`. There is no flag, no
 * env var and no config entry that promotes one to a failure, and none is to be
 * added in a later "hardening" pass — see the rationale at W1.
 */
type Warnings = string[];

const EMPTY_REFORM: Reform = {
  law: "",
  journalOfficiel: "",
  publishedOn: "",
  transitionDeadline: "",
  operationalFrom: "",
  previousWilayaCount: -1,
  currentWilayaCount: -1,
  newWilayas: [],
};

/** A field that is either a non-empty string or exactly `null`. */
function readNullableString(
  container: Record<string, unknown>,
  key: string,
  where: string,
  failures: Failures,
): string | null {
  const value = container[key];
  if (value === null) return null;
  if (typeof value === "string") return value;
  failures.push(`[R0] ${where}: "${key}" must be a string or null, got ${describe(value)}`);
  return null;
}

function readReformEntry(raw: unknown, where: string, failures: Failures): ReformEntry {
  if (!isRecord(raw)) {
    failures.push(`[R0] ${where}: entry must be an object, got ${describe(raw)}`);
    return { code: "", nom_fr: "", parentCode: null, source: null, confidence: "unverified" };
  }
  const code = readString(raw, "code", where, failures);
  const label = `reform entry "${code}"`;
  const confidence = readString(raw, "confidence", label, failures);
  return {
    code,
    nom_fr: readString(raw, "nom_fr", label, failures),
    parentCode: readNullableString(raw, "parentCode", label, failures),
    source: readNullableString(raw, "source", label, failures),
    // Checked here, at first contact, so R4 can compare against a value it knows
    // is one of the three literals rather than against arbitrary text.
    confidence: isReformConfidence(confidence)
      ? confidence
      : (failures.push(
          `[R0] ${label}: "confidence" must be one of ` +
            `${REFORM_CONFIDENCE_VALUES.map((value) => `"${value}"`).join(", ")}, ` +
            `got ${describe(raw["confidence"])}`,
        ),
        "unverified"),
  };
}

function isReformConfidence(value: string): boolean {
  return (REFORM_CONFIDENCE_VALUES as readonly string[]).includes(value);
}

function readReform(failures: Failures): Reform {
  const raw = parseJsonText(readFileSync(join(REPO_ROOT, REFORM_REL), "utf8"));
  const where = REFORM_REL;
  if (!isRecord(raw)) {
    failures.push(`[R0] ${where}: root must be a JSON object, got ${describe(raw)}`);
    return EMPTY_REFORM;
  }
  const newWilayasRaw = readArray(raw, "newWilayas", where, failures);
  return {
    law: readString(raw, "law", where, failures),
    journalOfficiel: readString(raw, "journalOfficiel", where, failures),
    publishedOn: readString(raw, "publishedOn", where, failures),
    transitionDeadline: readString(raw, "transitionDeadline", where, failures),
    operationalFrom: readString(raw, "operationalFrom", where, failures),
    previousWilayaCount: readInteger(raw, "previousWilayaCount", where, failures),
    currentWilayaCount: readInteger(raw, "currentWilayaCount", where, failures),
    newWilayas: newWilayasRaw.map((entry, index) =>
      readReformEntry(entry, `${where} newWilayas[${index}]`, failures),
    ),
  };
}

function reformLabel(entry: ReformEntry): string {
  return `reform entry "${entry.code}"`;
}

/** The padded two-digit form of a wilaya code, the notation reform.json uses. */
function paddedCode(wilayaNum: number): string {
  return String(wilayaNum).padStart(2, "0");
}

/**
 * `true` only when the transcription is finished: all 11 entries carry a
 * parentCode among the wilayas mères, a non-empty citation, and `"confirmed"`.
 *
 * COMPUTED, never hand-written. The JSON file has no `mappingComplete` key at
 * all — if it did, a maintainer could set it to `true` over an unfilled table
 * and the reform API would start answering with nulls instead of throwing.
 */
function reformMappingComplete(reform: Reform): boolean {
  return (
    reform.newWilayas.length === REFORM_NEW_WILAYA_COUNT &&
    reform.newWilayas.every(
      (entry) =>
        entry.parentCode !== null &&
        isParentWilayaCode(entry.parentCode) &&
        entry.source !== null &&
        entry.source.trim() !== "" &&
        entry.confidence === "confirmed",
    )
  );
}

/** "01".."58" — a wilaya mère. Never "59".."69"; see R3. */
function isParentWilayaCode(code: string): boolean {
  const num = Number.parseInt(code, 10);
  return (
    /^\d{2}$/.test(code) && Number.isInteger(num) && num >= 1 && num <= REFORM_PREVIOUS_WILAYA_COUNT
  );
}

function reformFilledCount(reform: Reform): number {
  return reform.newWilayas.filter((entry) => entry.parentCode !== null).length;
}

/**
 * R1..R5 into `failures`, W1..W2 into `warnings`. Every check accumulates; not
 * one of them throws or returns early.
 */
function assertReform(
  source: Algeria,
  reform: Reform,
  failures: Failures,
  warnings: Warnings,
): void {
  const wilayaByCode = new Map<string, Wilaya>();
  for (const wilaya of source.wilayas) {
    const code = paddedCode(wilaya.wilaya_num);
    if (!wilayaByCode.has(code)) wilayaByCode.set(code, wilaya);
  }

  // --- R1. Exactly 11 entries, codes "59".."69" ascending, no gaps, no dups ---
  const count = reform.newWilayas.length;
  if (count !== REFORM_NEW_WILAYA_COUNT) {
    failures.push(
      `[R1] ${REFORM_REL}: expected ${REFORM_NEW_WILAYA_COUNT} newWilayas entries, found ${count}`,
    );
  }
  const seenCodes = new Map<string, string[]>();
  for (const [index, entry] of reform.newWilayas.entries()) {
    // Positional, which is what makes one loop cover "ascending", "no gaps" and
    // "no duplicates" at once: entry #n must be code 59 + n, or something is off.
    const expected = paddedCode(FIRST_NEW_WILAYA_CODE + index);
    if (entry.code !== expected) {
      failures.push(
        `[R1] ${reformLabel(entry)}: newWilayas[${index}] must be code "${expected}" — ` +
          `the ${REFORM_NEW_WILAYA_COUNT} entries are "${paddedCode(FIRST_NEW_WILAYA_CODE)}".."` +
          `${paddedCode(EXPECTED_WILAYA_COUNT)}" in ascending order, with no gaps`,
      );
    }
    // Reported separately from the positional check: a duplicate is a different
    // mistake from a gap, and the message that names both offending indexes is
    // the one a maintainer can act on.
    pushKey(seenCodes, entry.code, `newWilayas[${index}]`);
  }
  for (const [code, positions] of seenCodes) {
    if (positions.length > 1) {
      failures.push(
        `[R1] ${REFORM_REL}: code "${code}" appears ${positions.length} times, ` +
          `at ${positions.join(" AND ")}`,
      );
    }
  }

  for (const entry of reform.newWilayas) {
    const label = reformLabel(entry);

    // --- R2. nom_fr matches the dataset — catches a paste error outright ------
    const wilaya = wilayaByCode.get(entry.code);
    if (wilaya === undefined) {
      failures.push(`[R2] ${label}: no wilaya with code "${entry.code}" exists in ${SOURCE_REL}`);
    } else if (entry.nom_fr !== wilaya.nom_fr) {
      failures.push(
        `[R2] ${label}: nom_fr is "${entry.nom_fr}", but ${SOURCE_REL} names ` +
          `that wilaya "${wilaya.nom_fr}"`,
      );
    }

    // --- R3. A non-null parentCode is a real wilaya mère, "01".."58" ----------
    if (entry.parentCode !== null && !isParentWilayaCode(entry.parentCode)) {
      const num = Number.parseInt(entry.parentCode, 10);
      const why =
        Number.isInteger(num) && num >= FIRST_NEW_WILAYA_CODE && num <= EXPECTED_WILAYA_COUNT
          ? `"${entry.parentCode}" is itself one of the 11 new wilayas — a new wilaya ` +
            `cannot be another new wilaya's mère`
          : `"${entry.parentCode}" is not a wilaya code in "01".."` +
            `${paddedCode(REFORM_PREVIOUS_WILAYA_COUNT)}"`;
      failures.push(`[R3] ${label}: ${why}`);
    } else if (entry.parentCode !== null && !wilayaByCode.has(entry.parentCode)) {
      failures.push(
        `[R3] ${label}: parentCode "${entry.parentCode}" resolves to no wilaya in ${SOURCE_REL}`,
      );
    }

    // --- R4. "confirmed" costs a citation AND a parentCode --------------------
    // The gate that stops the unverified candidate table being pasted in and
    // rubber-stamped: claiming the law says something requires naming where.
    if (entry.confidence === "confirmed") {
      if (entry.source === null || entry.source.trim() === "") {
        failures.push(
          `[R4] ${label}: confidence is "confirmed" but source is ` +
            `${entry.source === null ? "null" : "empty"} — cite the Journal Officiel`,
        );
      }
      if (entry.parentCode === null) {
        failures.push(
          `[R4] ${label}: confidence is "confirmed" but parentCode is null — ` +
            `there is nothing to have confirmed`,
        );
      }
    }

    // --- R4b. A parentCode costs a citation, whatever the confidence says -----
    // R4 alone is one-directional, and the hole it leaves is the exact one this
    // whole design exists to close. `parentWilaya` is a PLAIN FIELD READ on the
    // Wilaya record: it does not consult `confidence`, it does not throw, and it
    // is served to every consumer the moment a non-null parentCode is emitted —
    // while `mappingComplete` may still be false and the resolvers may still be
    // refusing to answer. So a row left mid-transcription as
    //   { parentCode: "03", source: null, confidence: "unverified" }
    // would ship a GUESS with the full authority of a package that advertises
    // itself as handling the transition correctly, and a wrong parentWilaya
    // misroutes real postal mail and real government paperwork.
    //
    // Hence the symmetric rule: supplying a parent is the act that requires the
    // citation, not labelling it "confirmed". The two together mean a value can
    // only reach `parentWilaya` sourced. Note this cannot be caught downstream —
    // W1 stays SILENT on exactly this case, because a postal-prefix guess agrees
    // with the postal-prefix cross-check by construction.
    if (entry.parentCode !== null) {
      if (entry.source === null || entry.source.trim() === "") {
        failures.push(
          `[R4] ${label}: parentCode is "${entry.parentCode}" but source is ` +
            `${entry.source === null ? "null" : "empty"} — cite the Journal Officiel. ` +
            `An unsourced parentCode is a guess, and it reaches consumers as ` +
            `getWilaya(${entry.code}).parentWilaya whether or not the mapping is complete`,
        );
      }
      if (entry.confidence === "unverified") {
        failures.push(
          `[R4] ${label}: parentCode is "${entry.parentCode}" but confidence is ` +
            `"unverified" — do not ship a value you have not verified. Set ` +
            `"probable" or "confirmed" once you have read the JO, or put the ` +
            `parentCode back to null`,
        );
      }
    }
  }

  // --- R5. The metadata of the law itself -----------------------------------
  if (reform.law.trim() === "") failures.push(`[R5] ${REFORM_REL}: "law" is empty`);
  if (reform.journalOfficiel.trim() === "") {
    failures.push(`[R5] ${REFORM_REL}: "journalOfficiel" is empty`);
  }
  const dates: ReadonlyArray<readonly [string, string]> = [
    ["publishedOn", reform.publishedOn],
    ["transitionDeadline", reform.transitionDeadline],
    ["operationalFrom", reform.operationalFrom],
  ];
  for (const [field, value] of dates) {
    if (!REFORM_DATE_PATTERN.test(value)) {
      failures.push(
        `[R5] ${REFORM_REL}: "${field}" must be an ISO YYYY-MM-DD date, got "${value}"`,
      );
    }
  }
  if (reform.previousWilayaCount !== REFORM_PREVIOUS_WILAYA_COUNT) {
    failures.push(
      `[R5] ${REFORM_REL}: previousWilayaCount is ${reform.previousWilayaCount}, ` +
        `expected ${REFORM_PREVIOUS_WILAYA_COUNT}`,
    );
  }
  if (reform.currentWilayaCount !== EXPECTED_WILAYA_COUNT) {
    failures.push(
      `[R5] ${REFORM_REL}: currentWilayaCount is ${reform.currentWilayaCount}, ` +
        `expected ${EXPECTED_WILAYA_COUNT}`,
    );
  }
  // Lexicographic comparison IS chronological for zero-padded ISO dates, which
  // is why the shape check above is not cosmetic.
  if (!(reform.publishedOn < reform.transitionDeadline)) {
    failures.push(
      `[R5] ${REFORM_REL}: publishedOn "${reform.publishedOn}" must precede ` +
        `transitionDeadline "${reform.transitionDeadline}"`,
    );
  }
  if (!(reform.transitionDeadline < reform.operationalFrom)) {
    failures.push(
      `[R5] ${REFORM_REL}: transitionDeadline "${reform.transitionDeadline}" must precede ` +
        `operationalFrom "${reform.operationalFrom}"`,
    );
  }

  warnReformPostalPrefix(reform, wilayaByCode, warnings);
  warnReformDairaCollisions(reform, wilayaByCode, warnings);
}

/**
 * W1 — postal-prefix cross-check. A WARNING, permanently.
 *
 * The first two digits of a commune's `code_postal` usually match its wilaya
 * code, so the majority prefix across a new wilaya's communes is a plausible
 * guess at its wilaya mère. It is only a guess. Measured on the 58 wilayas whose
 * answer we already know, the prefix disagrees with the commune's own wilaya
 * code for 94 of 1408 communes — 6.7 % — plus 25 communes with no postal code
 * at all.
 *
 * A rule that is wrong 6.7 % of the time on data we know is correct cannot gate
 * a build. Were this an assertion, the first maintainer to enter a
 * correct-but-prefix-divergent parentCode straight out of the Journal Officiel
 * would be told by a red CI run that the Journal Officiel is wrong — and the
 * likely fix would be to "correct" the law to match the postcodes.
 *
 * So: it prints, and the build carries on. There is deliberately NO flag, env
 * var or config that turns W1 (or W2) into a hard failure. Do not add one in a
 * later "hardening" pass.
 */
function warnReformPostalPrefix(
  reform: Reform,
  wilayaByCode: ReadonlyMap<string, Wilaya>,
  warnings: Warnings,
): void {
  for (const entry of reform.newWilayas) {
    if (entry.parentCode === null) continue; // nothing to cross-check yet
    const wilaya = wilayaByCode.get(entry.code);
    if (wilaya === undefined) continue; // R2 has already reported this

    const counts = new Map<string, number>();
    let withoutPostalCode = 0;
    for (const daira of wilaya.dairas) {
      for (const commune of daira.communes) {
        if (commune.code_postal === null) {
          withoutPostalCode += 1;
          continue;
        }
        const prefix = commune.code_postal.slice(0, 2);
        counts.set(prefix, (counts.get(prefix) ?? 0) + 1);
      }
    }
    if (counts.size === 0) continue;

    // Ties break on the lower prefix so the warning text is deterministic — a
    // build must not print different bytes on different runs, warnings included.
    let majority = "";
    let majorityCount = 0;
    for (const [prefix, prefixCount] of [...counts].sort((a, b) => (a[0] < b[0] ? -1 : 1))) {
      if (prefixCount > majorityCount) {
        majority = prefix;
        majorityCount = prefixCount;
      }
    }
    if (majority === entry.parentCode) continue;

    const total = [...counts.values()].reduce((sum, value) => sum + value, 0);
    warnings.push(
      `[W1] ${reformLabel(entry)} "${entry.nom_fr}": parentCode is "${entry.parentCode}" ` +
        `but the majority postal prefix is "${majority}" ` +
        `(${majorityCount}/${total} communes` +
        `${withoutPostalCode > 0 ? `, ${withoutPostalCode} with no postal code` : ""}). ` +
        `The postal prefix is a hint, not the law — if the Journal Officiel says ` +
        `"${entry.parentCode}", it is right and this line is noise.`,
    );
  }
}

/**
 * W2 — daïra re-attachment collision. A WARNING, permanently.
 *
 * Under the `asOf: "58"` projection every new wilaya's daïras are re-attached to
 * its mère. If a daïra name then appears twice under one mère, that is worth
 * seeing — but it is not an error: a daïra genuinely split by the reform SHOULD
 * re-merge by name under its mère, which is exactly the shape this detects. It
 * informs; it never gates. As with W1, there is no flag that promotes it.
 */
function warnReformDairaCollisions(
  reform: Reform,
  wilayaByCode: ReadonlyMap<string, Wilaya>,
  warnings: Warnings,
): void {
  /** parentCode -> daira nom_fr -> the labels of the wilayas contributing it. */
  const byParent = new Map<string, Map<string, string[]>>();

  const contribute = (parentCode: string, wilaya: Wilaya): void => {
    let names = byParent.get(parentCode);
    if (names === undefined) {
      names = new Map<string, string[]>();
      byParent.set(parentCode, names);
    }
    for (const daira of wilaya.dairas) pushKey(names, daira.nom_fr, wilayaLabel(wilaya));
  };

  for (const entry of reform.newWilayas) {
    if (entry.parentCode === null) continue;
    const parent = wilayaByCode.get(entry.parentCode);
    const child = wilayaByCode.get(entry.code);
    if (parent === undefined || child === undefined) continue; // R2/R3 reported it
    // The mère's own daïras are contributed once, the first time it is named.
    if (!byParent.has(entry.parentCode)) contribute(entry.parentCode, parent);
    contribute(entry.parentCode, child);
  }

  for (const [parentCode, names] of byParent) {
    for (const [nomFr, owners] of names) {
      if (owners.length < 2) continue;
      warnings.push(
        `[W2] reform asOf:"58": wilaya mère "${parentCode}" would hold ${owners.length} ` +
          `daïras named "${nomFr}" (${owners.join(" AND ")}) — expected if the reform split ` +
          `that daïra, since the two halves re-merge by name under the mère.`,
      );
    }
  }
}

/**
 * `generated/reform.ts`.
 *
 * Codes are emitted as NUMBERS. The JSON file keeps zero-padded strings, which
 * is both `data/algeria.json`'s `code` field and the Journal Officiel's own
 * notation; `WilayaCode` in the library is the number union 1..69, so the
 * conversion happens here rather than in every consumer.
 *
 * `REFORM_RAW: ReformRaw`, NOT `as const` — and this is load-bearing. `as const`
 * would give `mappingComplete` the literal type `false` and every `parentCode`
 * the type `null`, so filling the mapping in would CHANGE THE PUBLIC TYPES.
 * Decision 5b forbids exactly that: a conditionally-present type surface makes
 * tsc, publint and attw produce different results from the same source tree.
 * The literal types on the seven metadata fields are wanted — they are constants
 * of the law, not of the transcription's progress — so they are declared on the
 * interface, from the data, and the annotation keeps the value widened.
 *
 * `nom_fr` and `todo` are NOT emitted: review aids for the JSON file, not
 * payload. The names already ship in generated/wilayas.ts.
 */
function emitReform(reform: Reform): string {
  const rows = reform.newWilayas.map((entry) => {
    const parentCode =
      entry.parentCode === null ? "null" : String(Number.parseInt(entry.parentCode, 10));
    const citation = entry.source === null ? "null" : tsString(entry.source);
    return (
      `    { code: ${String(Number.parseInt(entry.code, 10))}, parentCode: ${parentCode}, ` +
      `source: ${citation}, confidence: ${tsString(entry.confidence)} },`
    );
  });
  return [
    BANNER,
    "",
    'import type { WilayaCode } from "./codes";',
    "",
    'export type ReformConfidence = "confirmed" | "probable" | "unverified";',
    "",
    "export interface ReformRawEntry {",
    "  readonly code: WilayaCode;",
    "  readonly parentCode: WilayaCode | null;",
    "  readonly source: string | null;",
    "  readonly confidence: ReformConfidence;",
    "}",
    "",
    "export interface ReformRaw {",
    `  readonly law: ${tsString(reform.law)};`,
    `  readonly journalOfficiel: ${tsString(reform.journalOfficiel)};`,
    `  readonly publishedOn: ${tsString(reform.publishedOn)};`,
    `  readonly transitionDeadline: ${tsString(reform.transitionDeadline)};`,
    `  readonly operationalFrom: ${tsString(reform.operationalFrom)};`,
    `  readonly previousWilayaCount: ${reform.previousWilayaCount};`,
    `  readonly currentWilayaCount: ${reform.currentWilayaCount};`,
    "  readonly mappingComplete: boolean;",
    "  readonly newWilayas: readonly ReformRawEntry[];",
    "}",
    "",
    "export const REFORM_RAW: ReformRaw = {",
    `  law: ${tsString(reform.law)},`,
    `  journalOfficiel: ${tsString(reform.journalOfficiel)},`,
    `  publishedOn: ${tsString(reform.publishedOn)},`,
    `  transitionDeadline: ${tsString(reform.transitionDeadline)},`,
    `  operationalFrom: ${tsString(reform.operationalFrom)},`,
    `  previousWilayaCount: ${reform.previousWilayaCount},`,
    `  currentWilayaCount: ${reform.currentWilayaCount},`,
    `  mappingComplete: ${reformMappingComplete(reform) ? "true" : "false"},`,
    "  newWilayas: [",
    ...rows,
    "  ],",
    "};",
    "",
  ].join("\n");
}

/* =========================================================================== *
 * Entry point
 * =========================================================================== */

async function main(): Promise<void> {
  const checkOnly = process.argv.slice(2).includes("--check");
  const failures: Failures = [];
  const warnings: Warnings = [];

  // Phase 1
  const source = readSource(failures);
  const overrides = readOverrides(failures);
  const reform = readReform(failures);

  // Phase 5 — the model has to exist before the gate: assertions 5, 17, 18 and
  // 19 are checks on the ids it mints.
  const model = buildModel(source, overrides, failures);

  // Phase 2
  assertIntegrity(source, model, failures);

  // Phase 7 — into the SAME accumulator, so one run reports everything.
  assertReform(source, reform, failures, warnings);

  if (failures.length > 0) {
    for (const failure of failures) console.error(failure);
    console.error(`build-data: ${failures.length} check(s) failed — nothing was written`);
    // process.exitCode, not process.exit(): console.error to a pipe is async on
    // POSIX, so exiting here can truncate the very report we took care to
    // accumulate (e.g. `pnpm build:data 2>&1 | tee build.log` in CI).
    process.exitCode = 1;
    return;
  }

  // Phases 3 and 6
  const outputs = [
    ...projectJsonOutputs(source),
    ...emitTypeScriptOutputs(model, source, reform),
    ...fixtureOutputs(model),
  ];

  // Phase 4, in two passes.
  //
  // The search fixture is produced last and on its own because search.ts reads
  // generated/search-keys.ts: in a write run that file has to be on disk before
  // the import, or the fixture would record the PREVIOUS build's answers while
  // every other output moved forward — a drift the fixtures exist to prevent.
  if (!checkOnly) writeOutputs(outputs);

  const allOutputs = [...outputs, await searchFixtureOutput()];

  if (checkOnly) {
    // One check pass over everything, so findOrphans() sees the full expected
    // set. Checking in two passes would report the search fixture as an orphan.
    const differing = checkOutputs(allOutputs);
    if (differing.length > 0) {
      console.error(
        `build-data --check: ${differing.length} of ${allOutputs.length} outputs are out of date ` +
          `— run \`pnpm build:data\``,
      );
      for (const relPath of differing) console.error(relPath);
      process.exitCode = 1;
      return;
    }
  } else {
    writeOutputs(allOutputs.slice(outputs.length));
  }

  // Warnings first, so the success lines are the last thing on the terminal and
  // a warning cannot be mistaken for a consequence of them. console.warn, not
  // console.error: these are stderr notes about a build that SUCCEEDED, and
  // nothing here has touched process.exitCode.
  for (const warning of warnings) console.warn(warning);

  const withPostalCode = model.communes.filter((commune) => commune.postalCode !== null).length;
  console.log(
    `build-data: ${model.wilayas.length} wilayas, ${model.dairas.length} dairas, ` +
      `${model.communes.length} communes, ${withPostalCode} postal codes, ` +
      `${model.communes.length - withPostalCode} missing — all checks pass`,
  );

  const filled = reformFilledCount(reform);
  const total = reform.newWilayas.length;
  console.log(
    reformMappingComplete(reform)
      ? `build-data: reform ${filled}/${total} parentCode filled and sourced, ` +
          `mappingComplete=true — ${warnings.length} warnings`
      : `build-data: reform ${filled}/${total} parentCode filled, mappingComplete=false — ` +
          `asOf/resolve* API will throw`,
  );
}

/**
 * Only run when this file is the process entry point — `tests/slug.test.ts`
 * imports `slug` from here, and importing must not regenerate 77 files.
 *
 * Compared by resolved URL only. A basename comparison would fire for any
 * process whose argv[1] merely ends in "build-data.ts", and what it triggers
 * writes 77 files — too broad a trigger for a side effect that large.
 */
const entryPath = process.argv[1];
const isEntryPoint =
  entryPath !== undefined && pathToFileURL(resolve(entryPath)).href === import.meta.url;

if (isEntryPoint) {
  // main() is async only because the search fixture needs a dynamic import.
  // An unhandled rejection would exit 0 on some Node versions, so the failure
  // path is made explicit rather than left to the default handler.
  main().catch((error: unknown) => {
    console.error(error);
    process.exitCode = 1;
  });
}
