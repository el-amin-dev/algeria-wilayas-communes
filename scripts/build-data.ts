type Failures = string[];

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

/** Human-readable description of an unexpected value, for failure messages. */
function describe(value: unknown): string {
  if (value === null) return "null";
  if (Array.isArray(value)) return "an array";
  switch (typeof value) {
    case "undefined":
      return "undefined (the field is absent)";
    case "string":
      return `the string ${JSON.stringify(value)}`;
    case "number":
      return `the number ${value}`;
    case "boolean":
      return value ? "the boolean true" : "the boolean false";
    case "object":
      return "an object";
    default:
      return `a ${typeof value}`;
  }
}

function parseJsonText(text: string): unknown {
  const parsed: unknown = JSON.parse(text);
  return parsed;
}

function readString(
  container: Record<string, unknown>,
  key: string,
  where: string,
  failures: Failures,
): string {
  const value = container[key];
  if (typeof value === "string") return value;
  failures.push(`[A0] ${where}: "${key}" must be a string, got ${describe(value)}`);
  return "";
}

function readInteger(
  container: Record<string, unknown>,
  key: string,
  where: string,
  failures: Failures,
): number {
  const value = container[key];
  if (typeof value === "number" && Number.isInteger(value)) return value;
  failures.push(`[A0] ${where}: "${key}" must be an integer, got ${describe(value)}`);
  return -1;
}

function readArray(
  container: Record<string, unknown>,
  key: string,
  where: string,
  failures: Failures,
): readonly unknown[] {
  const value = container[key];
  if (Array.isArray(value)) return value;
  failures.push(`[A0] ${where}: "${key}" must be an array, got ${describe(value)}`);
  return [];
}

/**
 * Assertion 10 lives here, at the point of first contact with the value:
 * `code_postal` is either exactly `null` or a five-digit string. Not
 * `undefined`, not `""`, not a number.
 */
function readPostalCode(
  container: Record<string, unknown>,
  where: string,
  failures: Failures,
): string | null {
  const value = container["code_postal"];
  if (value === null) return null;
  if (typeof value === "string" && POSTAL_CODE_PATTERN.test(value)) return value;
  failures.push(
    `[A10] ${where}: "code_postal" must be null or a 5-digit string, got ${describe(value)}`,
  );
  return null;
}

function readCommune(raw: unknown, where: string, failures: Failures): Commune {
  if (!isRecord(raw)) {
    failures.push(`[A0] ${where}: commune must be an object, got ${describe(raw)}`);
    return { nom_ar: "", nom_fr: "", nom_en: "", code_postal: null };
  }
  const nom_fr = readString(raw, "nom_fr", where, failures);
  const label = `${where} "${nom_fr}"`;
  return {
    nom_ar: readString(raw, "nom_ar", label, failures),
    nom_fr,
    nom_en: readString(raw, "nom_en", label, failures),
    code_postal: readPostalCode(raw, label, failures),
  };
}

function readDaira(raw: unknown, where: string, failures: Failures): Daira {
  if (!isRecord(raw)) {
    failures.push(`[A0] ${where}: daira must be an object, got ${describe(raw)}`);
    return { nom_ar: "", nom_fr: "", nom_en: "", communes: [], nb_communes: -1 };
  }
  const nom_fr = readString(raw, "nom_fr", where, failures);
  const label = `${where} "${nom_fr}"`;
  const communesRaw = readArray(raw, "communes", label, failures);
  return {
    nom_ar: readString(raw, "nom_ar", label, failures),
    nom_fr,
    nom_en: readString(raw, "nom_en", label, failures),
    communes: communesRaw.map((entry, index) =>
      readCommune(entry, `${label} › commune #${index + 1}`, failures),
    ),
    nb_communes: readInteger(raw, "nb_communes", label, failures),
  };
}

function readWilaya(raw: unknown, where: string, failures: Failures): Wilaya {
  if (!isRecord(raw)) {
    failures.push(`[A0] ${where}: wilaya must be an object, got ${describe(raw)}`);
    return {
      wilaya_num: -1,
      code: "",
      nom_ar: "",
      nom_fr: "",
      nom_en: "",
      nb_dairas: -1,
      nb_communes: -1,
      dairas: [],
    };
  }
  const wilaya_num = readInteger(raw, "wilaya_num", where, failures);
  const nom_fr = readString(raw, "nom_fr", where, failures);
  const label = `wilaya ${wilaya_num} "${nom_fr}"`;
  const dairasRaw = readArray(raw, "dairas", label, failures);
  return {
    wilaya_num,
    code: readString(raw, "code", label, failures),
    nom_ar: readString(raw, "nom_ar", label, failures),
    nom_fr,
    nom_en: readString(raw, "nom_en", label, failures),
    nb_dairas: readInteger(raw, "nb_dairas", label, failures),
    nb_communes: readInteger(raw, "nb_communes", label, failures),
    dairas: dairasRaw.map((entry, index) =>
      readDaira(entry, `${label} › daira #${index + 1}`, failures),
    ),
  };
}

const EMPTY_PAYS: Pays = { nom_ar: "", nom_fr: "", nom_en: "", code_iso: "" };

function readPays(container: Record<string, unknown>, where: string, failures: Failures): Pays {
  const value = container["pays"];
  if (!isRecord(value)) {
    failures.push(`[A0] ${where}: "pays" must be an object, got ${describe(value)}`);
    return EMPTY_PAYS;
  }
  const label = `${where} › pays`;
  return {
    nom_ar: readString(value, "nom_ar", label, failures),
    nom_fr: readString(value, "nom_fr", label, failures),
    nom_en: readString(value, "nom_en", label, failures),
    code_iso: readString(value, "code_iso", label, failures),
  };
}

/** An array whose every element must be a string — `langues` and `sources`. */
function readStringArray(
  container: Record<string, unknown>,
  key: string,
  where: string,
  failures: Failures,
): string[] {
  return readArray(container, key, where, failures).map((entry, index) => {
    if (typeof entry === "string") return entry;
    failures.push(`[A0] ${where}: ${key}[${index}] must be a string, got ${describe(entry)}`);
    return "";
  });
}

function readSource(failures: Failures): Algeria {
  const raw = parseJsonText(readFileSync(join(REPO_ROOT, SOURCE_REL), "utf8"));
  const where = SOURCE_REL;
  if (!isRecord(raw)) {
    failures.push(`[A0] ${where}: root must be a JSON object, got ${describe(raw)}`);
    return {
      pays: EMPTY_PAYS,
      langues: [],
      reforme: "",
      hierarchie: "",
      note_daira: "",
      sources: [],
      nb_wilayas: -1,
      nb_dairas: -1,
      nb_communes: -1,
      codes_postaux_renseignes: -1,
      codes_postaux_manquants: -1,
      wilayas: [],
    };
  }
  const langues = readStringArray(raw, "langues", where, failures);
  const wilayasRaw = readArray(raw, "wilayas", where, failures);
  return {
    pays: readPays(raw, where, failures),
    langues,
    reforme: readString(raw, "reforme", where, failures),
    hierarchie: readString(raw, "hierarchie", where, failures),
    note_daira: readString(raw, "note_daira", where, failures),
    sources: readStringArray(raw, "sources", where, failures),
    nb_wilayas: readInteger(raw, "nb_wilayas", where, failures),
    nb_dairas: readInteger(raw, "nb_dairas", where, failures),
    nb_communes: readInteger(raw, "nb_communes", where, failures),
    codes_postaux_renseignes: readInteger(raw, "codes_postaux_renseignes", where, failures),
    codes_postaux_manquants: readInteger(raw, "codes_postaux_manquants", where, failures),
    wilayas: wilayasRaw.map((entry, index) =>
      readWilaya(entry, `${where} wilayas[${index}]`, failures),
    ),
  };
}

/**
 * `data/raw/en-overrides.json` — `{"<kind>:<id>": "<English name>"}` where kind
 * is `wilaya` | `daira` | `commune`, the id of a wilaya is its `wilaya_num` and
 * the id of a daira/commune is its slug id (phase 5).
 */
function readOverrides(failures: Failures): ReadonlyMap<string, string> {
  const raw = parseJsonText(readFileSync(join(REPO_ROOT, OVERRIDES_REL), "utf8"));
  const overrides = new Map<string, string>();
  if (!isRecord(raw)) {
    failures.push(`[A0] ${OVERRIDES_REL}: root must be a JSON object, got ${describe(raw)}`);
    return overrides;
  }
  for (const [key, value] of Object.entries(raw)) {
    if (typeof value !== "string" || value.trim() === "") {
      failures.push(
        `[A0] ${OVERRIDES_REL}: "${key}" must map to a non-empty string, got ${describe(value)}`,
      );
      continue;
    }
    overrides.set(key, value);
  }
  return overrides;
}

/* =========================================================================== *
 * Phase 2 — assert
 *
 * 19 checks. EVERY failure is accumulated; the caller prints them all, one per
 * line, and exits 1. Nothing stops at the first failure — `shared/validate.py`
 * reports all violations and this must match that behaviour.
 * =========================================================================== */

function wilayaLabel(wilaya: Wilaya): string {
  return `wilaya ${wilaya.wilaya_num} "${wilaya.nom_fr}"`;
}

function assertIntegrity(source: Algeria, model: Model, failures: Failures): void {
  // --- 1. Exactly 69 wilayas, wilaya_num contiguous 1..69, no gaps, no dups ---
  const wilayaCount = source.wilayas.length;
  if (wilayaCount !== EXPECTED_WILAYA_COUNT) {
    failures.push(`[A1] expected ${EXPECTED_WILAYA_COUNT} wilayas, found ${wilayaCount}`);
  }
  const wilayaNums = new Map<number, string[]>();
  for (const wilaya of source.wilayas) {
    const labels = wilayaNums.get(wilaya.wilaya_num);
    if (labels === undefined) wilayaNums.set(wilaya.wilaya_num, [wilayaLabel(wilaya)]);
    else labels.push(wilayaLabel(wilaya));
  }
  for (const [num, labels] of wilayaNums) {
    if (labels.length > 1) {
      failures.push(`[A1] duplicate wilaya_num ${num}: ${labels.join(" and ")}`);
    }
    if (num < 1 || num > EXPECTED_WILAYA_COUNT) {
      failures.push(
        `[A1] wilaya_num ${num} is outside the contiguous range 1..${EXPECTED_WILAYA_COUNT}`,
      );
    }
  }
  for (let num = 1; num <= EXPECTED_WILAYA_COUNT; num += 1) {
    if (!wilayaNums.has(num)) failures.push(`[A1] wilaya_num ${num} is missing from the tree`);
  }

  // --- 2. code === String(wilaya_num).padStart(2, "0") ------------------------
  for (const wilaya of source.wilayas) {
    const expected = String(wilaya.wilaya_num).padStart(2, "0");
    if (wilaya.code !== expected) {
      const label = wilayaLabel(wilaya);
      failures.push(`[A2] ${label}: code is "${wilaya.code}", expected "${expected}"`);
    }
  }

  // --- 3 & 4. Walked daira and commune totals --------------------------------
  let walkedDairas = 0;
  let walkedCommunes = 0;
  for (const wilaya of source.wilayas) {
    walkedDairas += wilaya.dairas.length;
    for (const daira of wilaya.dairas) walkedCommunes += daira.communes.length;
  }
  if (walkedDairas !== EXPECTED_DAIRA_COUNT) {
    failures.push(
      `[A3] expected ${EXPECTED_DAIRA_COUNT} dairas in the tree, walked ${walkedDairas}`,
    );
  }
  if (walkedCommunes !== EXPECTED_COMMUNE_COUNT) {
    failures.push(
      `[A4] expected ${EXPECTED_COMMUNE_COUNT} communes in the tree, walked ${walkedCommunes}`,
    );
  }

  // --- 5. Every commune resolves to a valid parent daira and wilaya ----------
  // Checked in buildModel(), where the flat rows are actually built.

  // --- 6, 7, 8. Per-record consistency ---------------------------------------
  for (const wilaya of source.wilayas) {
    const summed = wilaya.dairas.reduce((total, daira) => total + daira.nb_communes, 0);
    if (wilaya.nb_communes !== summed) {
      failures.push(
        `[A6] ${wilayaLabel(wilaya)}: nb_communes is ${wilaya.nb_communes}, ` +
          `its dairas sum to ${summed}`,
      );
    }
    if (wilaya.nb_dairas !== wilaya.dairas.length) {
      failures.push(
        `[A7] ${wilayaLabel(wilaya)}: nb_dairas is ${wilaya.nb_dairas}, ` +
          `dairas[] has ${wilaya.dairas.length} entries`,
      );
    }
    for (const daira of wilaya.dairas) {
      if (daira.nb_communes !== daira.communes.length) {
        failures.push(
          `[A8] ${wilayaLabel(wilaya)} › daira "${daira.nom_fr}": nb_communes is ` +
            `${daira.nb_communes}, communes[] has ${daira.communes.length} entries`,
        );
      }
    }
  }

  // --- 9. Top-level counters, against both the constants and the walk --------
  const topLevel: ReadonlyArray<readonly [string, number, number, number]> = [
    ["nb_wilayas", source.nb_wilayas, EXPECTED_WILAYA_COUNT, source.wilayas.length],
    ["nb_dairas", source.nb_dairas, EXPECTED_DAIRA_COUNT, walkedDairas],
    ["nb_communes", source.nb_communes, EXPECTED_COMMUNE_COUNT, walkedCommunes],
  ];
  for (const [field, declared, expected, walked] of topLevel) {
    if (declared !== expected) {
      failures.push(`[A9] ${SOURCE_REL}: ${field} is ${declared}, expected ${expected}`);
    }
    if (declared !== walked) {
      failures.push(
        `[A9] ${SOURCE_REL}: ${field} is ${declared} but the tree walk counted ${walked}`,
      );
    }
  }

  // --- 10. code_postal shape ------------------------------------------------
  // Checked in readPostalCode(), at the point of first contact with the value.

  // --- 11. nom_ar present and non-empty everywhere ---------------------------
  for (const wilaya of source.wilayas) {
    if (wilaya.nom_ar.trim() === "") {
      failures.push(`[A11] ${wilayaLabel(wilaya)}: nom_ar is empty`);
    }
    for (const daira of wilaya.dairas) {
      if (daira.nom_ar.trim() === "") {
        failures.push(`[A11] ${wilayaLabel(wilaya)} › daira "${daira.nom_fr}": nom_ar is empty`);
      }
      for (const commune of daira.communes) {
        if (commune.nom_ar.trim() === "") {
          failures.push(
            `[A11] ${wilayaLabel(wilaya)} › daira "${daira.nom_fr}" › ` +
              `commune "${commune.nom_fr}": nom_ar is empty`,
          );
        }
      }
    }
  }

  // --- 12 & 13. Composite-key uniqueness ------------------------------------
  // A13 is load-bearing: a daira id is <wilaya code>-<slug(nom_fr)>, so two
  // same-named daïras in one wilaya collide outright.
  //
  // A12 is STRICTER than what id-safety needs, and deliberately so. A commune id
  // carries its daira, so two same-named communes in *different* daïras of one
  // wilaya would get distinct ids and be perfectly safe — A19 checks id
  // uniqueness directly and is the real gate for that. A12 is a data-quality
  // signal: the dataset has no such pair today (verified: 1541 distinct
  // (wilaya, name) keys), and a new one almost certainly means a duplicated
  // record rather than a genuine second commune. If a real one is ever added,
  // relax this to A19 rather than weakening A19.
  const communeKeys = new Map<string, string[]>();
  const dairaKeys = new Map<string, string[]>();
  for (const wilaya of source.wilayas) {
    const wLabel = wilayaLabel(wilaya);
    for (const [dairaIndex, daira] of wilaya.dairas.entries()) {
      // The positional index is part of the label so that two records sharing a
      // name — which is exactly the case being reported — stay distinguishable.
      const dLabel = `${wLabel} › daira #${dairaIndex + 1} "${daira.nom_fr}"`;
      pushKey(dairaKeys, `${wilaya.wilaya_num}|${daira.nom_fr}`, dLabel);
      for (const [communeIndex, commune] of daira.communes.entries()) {
        const cKey = `${wilaya.wilaya_num}|${commune.nom_fr}`;
        pushKey(communeKeys, cKey, `${dLabel} › commune #${communeIndex + 1} "${commune.nom_fr}"`);
      }
    }
  }
  reportDuplicateKeys(communeKeys, "A12", "wilaya_num, commune nom_fr", failures);
  reportDuplicateKeys(dairaKeys, "A13", "wilaya_num, daira nom_fr", failures);

  // --- 14, 15, 16. The metadata counters ------------------------------------
  // A NEW gate: shared/validate.py never checked any of these three, so the
  // two counters could drift away from the records they describe.
  const withPostalCode = model.communes.filter((commune) => commune.postalCode !== null).length;
  const missingPostalCode = model.communes.length - withPostalCode;
  if (source.codes_postaux_renseignes !== withPostalCode) {
    failures.push(
      `[A14] ${SOURCE_REL}: codes_postaux_renseignes is ${source.codes_postaux_renseignes}, ` +
        `but ${withPostalCode} communes actually carry a postal code`,
    );
  }
  if (source.codes_postaux_manquants !== missingPostalCode) {
    failures.push(
      `[A15] ${SOURCE_REL}: codes_postaux_manquants is ${source.codes_postaux_manquants}, ` +
        `but ${missingPostalCode} communes actually have code_postal: null`,
    );
  }
  const declaredTotal = source.codes_postaux_renseignes + source.codes_postaux_manquants;
  if (declaredTotal !== source.nb_communes) {
    failures.push(
      `[A16] ${SOURCE_REL}: codes_postaux_renseignes + codes_postaux_manquants = ` +
        `${declaredTotal}, expected nb_communes = ${source.nb_communes}`,
    );
  }

  // --- 17, 18, 19. Overrides and ids ----------------------------------------
  // Checked in buildModel(), which is where the ids are minted.
}

function pushKey(index: Map<string, string[]>, key: string, label: string): void {
  const existing = index.get(key);
  if (existing === undefined) index.set(key, [label]);
  else existing.push(label);
}

/** Reports every composite key claimed by more than one record, naming them all. */
function reportDuplicateKeys(
  index: ReadonlyMap<string, string[]>,
  code: string,
  what: string,
  failures: Failures,
): void {
  for (const [key, labels] of index) {
    if (labels.length > 1) {
      failures.push(`[${code}] duplicate (${what}) "${key}": ${labels.join(" AND ")}`);
    }
  }
}

/**
 * Assertion 19 — mints one id at a time and fails on a collision, naming BOTH
 * offending records. All 591 daira ids and all 1541 commune ids must be unique.
 */
function claimId(
  owners: Map<string, string>,
  id: string,
  label: string,
  kind: string,
  failures: Failures,
): void {
  const owner = owners.get(id);
  if (owner === undefined) owners.set(id, label);
  else failures.push(`[A19] duplicate ${kind} id "${id}": ${owner} AND ${label}`);
}

/* =========================================================================== *
 * Phase 3 — project the four JSON outputs
 *
 * Every field is written EXPLICITLY, in the exact order of the frozen contract.
 * Never build these with spread (`{...w, extra}`): key-insertion order in the
 * object literal IS the emitted key order, and spreading makes that order
 * depend on the input. Reordering a property below silently breaks the
 * byte-identity gate.
 *
 * Iteration is document order throughout — wilayas 1→69, daïras in array order,
 * communes in array order. NO SORTING, EVER.
 * =========================================================================== */

function projectJsonOutputs(source: Algeria): Output[] {
  const outputs: Output[] = [];

  // data/wilayas.json
  outputs.push({
    kind: "json",
    relPath: "data/wilayas.json",
    value: {
      langues: source.langues,
      nb_wilayas: source.nb_wilayas,
      wilayas: source.wilayas.map((wilaya) => ({
        wilaya_num: wilaya.wilaya_num,
        code: wilaya.code,
        nom_ar: wilaya.nom_ar,
        nom_fr: wilaya.nom_fr,
        nom_en: wilaya.nom_en,
        nb_dairas: wilaya.nb_dairas,
        nb_communes: wilaya.nb_communes,
      })),
    },
  });

  // data/dairas.json
  //
  // !! READ BEFORE "FIXING" THE MISSING wilaya_ar BELOW !!
  //
  // Daira rows carry wilaya_fr and wilaya_en but NO wilaya_ar, while commune
  // rows carry all three. That is almost certainly an oversight in the original
  // jq filter this function replaces — and it is reproduced here deliberately.
  //
  // data/*.json is a PUBLISHED CONTRACT: it is consumed over the jsDelivr CDN
  // and by the jq, Python and Java examples in the root README. Adding the field
  // changes the byte output, fails `git diff --exit-code data/`, and silently
  // changes what every CDN consumer receives. It is recorded as a CANDIDATE v3
  // CHANGE — a major-version data break — not something to slip in here.
  //
  // The same discipline applies to the daira key order in the per-wilaya files
  // below, where `nb_communes` comes AFTER the `communes` array. Do not tidy it.
  outputs.push({
    kind: "json",
    relPath: "data/dairas.json",
    value: {
      nb_dairas: source.nb_dairas,
      dairas: source.wilayas.flatMap((wilaya) =>
        wilaya.dairas.map((daira) => ({
          wilaya_num: wilaya.wilaya_num,
          wilaya_code: wilaya.code,
          wilaya_fr: wilaya.nom_fr,
          wilaya_en: wilaya.nom_en,
          nom_ar: daira.nom_ar,
          nom_fr: daira.nom_fr,
          nom_en: daira.nom_en,
          nb_communes: daira.nb_communes,
        })),
      ),
    },
  });

  // data/communes.json — this one DOES have wilaya_ar. See the note above.
  outputs.push({
    kind: "json",
    relPath: "data/communes.json",
    value: {
      nb_communes: source.nb_communes,
      communes: source.wilayas.flatMap((wilaya) =>
        wilaya.dairas.flatMap((daira) =>
          daira.communes.map((commune) => ({
            wilaya_num: wilaya.wilaya_num,
            wilaya_code: wilaya.code,
            wilaya_ar: wilaya.nom_ar,
            wilaya_fr: wilaya.nom_fr,
            wilaya_en: wilaya.nom_en,
            daira_ar: daira.nom_ar,
            daira_fr: daira.nom_fr,
            daira_en: daira.nom_en,
            nom_ar: commune.nom_ar,
            nom_fr: commune.nom_fr,
            nom_en: commune.nom_en,
            code_postal: commune.code_postal,
          })),
        ),
      ),
    },
  });

  // data/by-wilaya/NN.json — the ROOT is the wilaya object itself, no wrapper.
  //
  // Re-projected field by field rather than passed straight through from the
  // parsed source: re-projecting means this script *states* the contract instead
  // of inheriting it, so an unexpected new field in algeria.json shows up as a
  // visible diff instead of silently propagating into 69 published files.
  //
  // The filename uses the padded wilaya_num, which assertion 2 has already
  // proven equal to `code`.
  for (const wilaya of source.wilayas) {
    outputs.push({
      kind: "json",
      relPath: `${BY_WILAYA_DIR_REL}/${String(wilaya.wilaya_num).padStart(2, "0")}.json`,
      value: {
        wilaya_num: wilaya.wilaya_num,
        code: wilaya.code,
        nom_ar: wilaya.nom_ar,
        nom_fr: wilaya.nom_fr,
        nom_en: wilaya.nom_en,
        nb_dairas: wilaya.nb_dairas,
        nb_communes: wilaya.nb_communes,
        dairas: wilaya.dairas.map((daira) => ({
          nom_ar: daira.nom_ar,
          nom_fr: daira.nom_fr,
          nom_en: daira.nom_en,
          communes: daira.communes.map((commune) => ({
            nom_ar: commune.nom_ar,
            nom_fr: commune.nom_fr,
            nom_en: commune.nom_en,
            code_postal: commune.code_postal,
          })),
          // nb_communes LAST — frozen, deliberate, do not tidy.
          nb_communes: daira.nb_communes,
        })),
      },
    });
  }

  return outputs;
}

/* =========================================================================== *
 * Phase 4 — write, or compare in --check mode
 * =========================================================================== */

type Output =
  | { readonly kind: "json"; readonly relPath: string; readonly value: unknown }
  | { readonly kind: "text"; readonly relPath: string; readonly content: string };

/**
 * VERIFIED byte-identical against the committed files on Node v22: both `jq` and
 * `JSON.stringify` emit 2-space indentation and raw UTF-8 (neither escapes
 * non-ASCII). The only difference is jq's trailing newline — hence `+ "\n"`.
 */
function renderJson(value: unknown): string {
  return JSON.stringify(value, null, 2) + "\n";
}

/**
 * The single rendering helper for every one of the 77 outputs. Both the write
 * path and `--check` call it, which is what makes `--check` a true statement
 * about what a build would produce rather than a parallel reimplementation.
 */
function renderOutput(output: Output): string {
  return output.kind === "json" ? renderJson(output.value) : output.content;
}

/**
 * `data/by-wilaya/` and `packages/js/src/generated/` already exist. Files are
 * overwritten in place — the directories are NEVER cleared. A blind `rm -rf` on
 * a data directory is not worth the risk.
 */
function writeOutputs(outputs: readonly Output[]): void {
  for (const output of outputs) {
    const absPath = join(REPO_ROOT, output.relPath);
    mkdirSync(dirname(absPath), { recursive: true });
    // Deliberately the SAME renderOutput() that --check compares against: one
    // rendering path, so the two can never disagree about what a file should be.
    writeFileSync(absPath, renderOutput(output), "utf8");
  }
}

function readTextIfPresent(absPath: string): string | undefined {
  try {
    return readFileSync(absPath, "utf8");
  } catch {
    return undefined;
  }
}

/** @returns the relative paths that differ from what is on disk. */
function checkOutputs(outputs: readonly Output[]): string[] {
  const differing: string[] = [];
  for (const output of outputs) {
    const onDisk = readTextIfPresent(join(REPO_ROOT, output.relPath));
    if (onDisk === undefined) differing.push(`${output.relPath} (missing or unreadable)`);
    else if (onDisk !== renderOutput(output)) differing.push(output.relPath);
  }
  return [...differing, ...findOrphans(outputs)];
}

/**
 * Files sitting in an output directory that the build no longer produces.
 *
 * Comparing only the files we know about cannot see these, and `writeOutputs`
 * never clears a directory (deliberately — a blind rm -rf on data/ is not worth
 * the risk). So a stale `data/by-wilaya/70.json` left behind by a future count
 * change would keep shipping over jsDelivr with every gate green.
 */
function findOrphans(outputs: readonly Output[]): string[] {
  const expected = new Set(outputs.map((output) => output.relPath));
  const orphans: string[] = [];
  for (const dirRel of OUTPUT_DIRS) {
    let entries: string[];
    try {
      entries = readdirSync(join(REPO_ROOT, dirRel));
    } catch {
      continue;
    }
    for (const entry of entries) {
      const relPath = `${dirRel}/${entry}`;
      if (!expected.has(relPath)) orphans.push(`${relPath} (orphan — no longer generated)`);
    }
  }
  return orphans;
}

/* =========================================================================== *
 * Phase 5 — slug ids, English resolution, and the normalized model
 * =========================================================================== */

/**
 * Latin-only slug, used purely to mint ids from `nom_fr`.
 *
 *   1. lowercase
 *   2. NFD normalize, then strip combining marks  (this is what turns é into e)
 *   3. REMOVE apostrophes (' and ’) — delete them, never hyphenate them
 *   4. whitespace → "-"
 *   5. drop every character that is not [a-z0-9-]
 *   6. collapse runs of "-"
 *   7. trim leading and trailing "-"
 *
 * Step 3 deletes rather than hyphenates because that is what the data needs:
 * `M'Sila` → `msila` and `Sidi M'hamed` → `sidi-mhamed`, not `m-sila` /
 * `sidi-m-hamed`. The seven fixtures below are asserted inline on every build.
 *
 * Arabic normalization for *search* is a different, larger problem and belongs
 * to the runtime API, not here.
 */
export function slug(input: string): string {
  return input
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/['’]/g, "")
    .replace(/\s+/g, "-")
    .replace(/[^a-z0-9-]/g, "")
    .replace(/-+/g, "-")
    .replace(/^-+|-+$/g, "");
}

const SLUG_FIXTURES: ReadonlyArray<readonly [string, string]> = [
  ["Sidi M'hamed", "sidi-mhamed"],
  ["M'Sila", "msila"],
  ["Abi-Youcef", "abi-youcef"],
  ["Alger Centre", "alger-centre"],
  ["Bordj Bou Arreridj", "bordj-bou-arreridj"],
  ["Béjaïa", "bejaia"],
  ["Aïn Témouchent", "ain-temouchent"],
];

/**
 * Assertion 20 — a slug must not come out empty.
 *
 * `slug()` strips everything outside [a-z0-9-], so a name with no Latin letters
 * at all (an Arabic string mistakenly entered in the nom_fr field, say) reduces
 * to "". That would mint ids like "09-" and "09--x" and ship them in the
 * published TypeScript with the build still exiting 0.
 */
function checkSlugNonEmpty(
  slugged: string,
  nomFr: string,
  label: string,
  failures: Failures,
): void {
  if (slugged.length > 0) return;
  failures.push(
    `[A20] ${label}: nom_fr "${nomFr}" slugs to the empty string — the id would be malformed`,
  );
}

function checkSlugFixtures(failures: Failures): void {
  for (const [input, expected] of SLUG_FIXTURES) {
    const actual = slug(input);
    if (actual !== expected) {
      failures.push(`[SLUG] slug("${input}") produced "${actual}", expected "${expected}"`);
    }
  }
}

interface LocalizedName {
  readonly ar: string;
  readonly fr: string;
  readonly en: string;
}

interface WilayaRecord {
  readonly code: number;
  readonly name: LocalizedName;
  readonly dairaCount: number;
  readonly communeCount: number;
}

interface DairaRecord {
  readonly id: string;
  readonly wilaya: number;
  readonly name: LocalizedName;
  readonly communeCount: number;
}

interface CommuneRecord {
  readonly id: string;
  readonly wilaya: number;
  readonly daira: string;
  readonly name: LocalizedName;
  readonly postalCode: string | null;
}

interface Model {
  readonly wilayas: readonly WilayaRecord[];
  readonly dairas: readonly DairaRecord[];
  readonly communes: readonly CommuneRecord[];
}

/**
 * Walks the tree in document order, minting ids and resolving English names.
 *
 * Ids (decision D2 — LIBRARY-ASSIGNED, NOT OFFICIAL):
 *
 *   daira id   = wilaya code + "-" + slug(daira nom_fr)      e.g. "16-baraki"
 *   commune id = daira id    + "-" + slug(commune nom_fr)    e.g. "16-baraki-baraki"
 *
 * The wilaya prefix is NOT optional: 38 commune nom_fr values are duplicated
 * across wilayas (`Sidi Ameur` in 32 and 64, `Souk El Had` in 35 and 48), and
 * there are only 545 distinct daira names for 591 daïras.
 *
 * English names are `override ?? nom_fr`. `nom_en` differs from `nom_fr` for
 * exactly ONE record in the whole dataset (wilaya 16, Alger → Algiers), so
 * shipping 2201 duplicate English strings would be ~99.9% wasted payload.
 *
 * Carries assertions 5, 17, 18 and 19.
 */
function buildModel(
  source: Algeria,
  overrides: ReadonlyMap<string, string>,
  failures: Failures,
): Model {
  checkSlugFixtures(failures);

  const wilayas: WilayaRecord[] = [];
  const dairas: DairaRecord[] = [];
  const communes: CommuneRecord[] = [];

  /** Every override key that a real record could claim — assertion 17. */
  const resolvableKeys = new Set<string>();
  /** id → the label of the record that claimed it first — assertion 19. */
  const dairaIdOwners = new Map<string, string>();
  const communeIdOwners = new Map<string, string>();

  const wilayaByNum = new Map<number, Wilaya>();
  for (const wilaya of source.wilayas) {
    if (!wilayaByNum.has(wilaya.wilaya_num)) wilayaByNum.set(wilaya.wilaya_num, wilaya);
  }

  for (const wilaya of source.wilayas) {
    const wKey = `wilaya:${wilaya.wilaya_num}`;
    resolvableKeys.add(wKey);
    const wLabel = wilayaLabel(wilaya);
    checkExonym(wilaya.nom_fr, wilaya.nom_en, wKey, wLabel, overrides, failures); // 18

    wilayas.push({
      code: wilaya.wilaya_num,
      name: {
        ar: wilaya.nom_ar,
        fr: wilaya.nom_fr,
        en: overrides.get(wKey) ?? wilaya.nom_fr,
      },
      dairaCount: wilaya.dairas.length,
      communeCount: wilaya.dairas.reduce((total, daira) => total + daira.communes.length, 0),
    });

    for (const [dairaIndex, daira] of wilaya.dairas.entries()) {
      const dairaSlug = slug(daira.nom_fr);
      checkSlugNonEmpty(dairaSlug, daira.nom_fr, `${wLabel} › daira "${daira.nom_fr}"`, failures);
      const dairaId = `${wilaya.code}-${dairaSlug}`;
      // The positional index keeps two same-named records distinguishable in a
      // collision report, which is precisely when it matters.
      const dLabel = `${wLabel} › daira #${dairaIndex + 1} "${daira.nom_fr}"`;

      claimId(dairaIdOwners, dairaId, dLabel, "daira", failures); // 19

      const dKey = `daira:${dairaId}`;
      resolvableKeys.add(dKey);
      checkExonym(daira.nom_fr, daira.nom_en, dKey, dLabel, overrides, failures); // 18

      dairas.push({
        id: dairaId,
        wilaya: wilaya.wilaya_num,
        name: {
          ar: daira.nom_ar,
          fr: daira.nom_fr,
          en: overrides.get(dKey) ?? daira.nom_fr,
        },
        communeCount: daira.communes.length,
      });

      for (const [communeIndex, commune] of daira.communes.entries()) {
        const communeSlug = slug(commune.nom_fr);
        checkSlugNonEmpty(communeSlug, commune.nom_fr, `${dLabel} › "${commune.nom_fr}"`, failures);
        const communeId = `${dairaId}-${communeSlug}`;
        const cLabel = `${dLabel} › commune #${communeIndex + 1} "${commune.nom_fr}"`;

        // 5 — a REFACTOR GUARD, not a data gate. As written these are tautologies
        // over the arrays being iterated, so no input can fail them; the spec
        // asks for the check anyway ("guaranteed by tree walking, but assert it
        // explicitly"). Its value is that if this loop is ever rewritten to join
        // flat rows by key instead of walking the tree, a detached commune stops
        // being impossible and these start earning their keep. Do not count it
        // among the assertions that actually gate the data.
        if (wilayaByNum.get(wilaya.wilaya_num) !== wilaya) {
          failures.push(`[A5] ${cLabel}: parent ${wLabel} does not resolve by wilaya_num`);
        }
        if (!wilaya.dairas.includes(daira)) {
          failures.push(`[A5] ${cLabel}: parent daira is not a member of ${wLabel}.dairas`);
        }
        if (!daira.communes.includes(commune)) {
          failures.push(`[A5] ${cLabel}: commune is not a member of its parent daira's communes`);
        }

        claimId(communeIdOwners, communeId, cLabel, "commune", failures); // 19

        const cKey = `commune:${communeId}`;
        resolvableKeys.add(cKey);
        checkExonym(commune.nom_fr, commune.nom_en, cKey, cLabel, overrides, failures); // 18

        communes.push({
          id: communeId,
          wilaya: wilaya.wilaya_num,
          daira: dairaId,
          name: {
            ar: commune.nom_ar,
            fr: commune.nom_fr,
            en: overrides.get(cKey) ?? commune.nom_fr,
          },
          postalCode: commune.code_postal,
        });
      }
    }
  }

  // 17 — an orphaned override (a rename, or a reform) must fail the build.
  for (const key of overrides.keys()) {
    if (!resolvableKeys.has(key)) {
      failures.push(
        `[A17] ${OVERRIDES_REL}: key "${key}" does not resolve to any record in ${SOURCE_REL}`,
      );
    }
  }

  return { wilayas, dairas, communes };
}

/**
 * Assertion 18 — a record whose `nom_en` differs from its `nom_fr` must have an
 * override entry, otherwise a new English name is silently dropped on the floor
 * when the generator falls back to `nom_fr`.
 */
function checkExonym(
  nomFr: string,
  nomEn: string,
  key: string,
  label: string,
  overrides: ReadonlyMap<string, string>,
  failures: Failures,
): void {
  if (nomEn === nomFr) return;
  const override = overrides.get(key);
  if (override === undefined) {
    failures.push(
      `[A18] ${label}: nom_en "${nomEn}" differs from nom_fr "${nomFr}" but ` +
        `${OVERRIDES_REL} has no "${key}" entry`,
    );
    return;
  }
  // Existence is not enough. data/wilayas.json emits nom_en straight from the
  // source while the generated TypeScript emits `override ?? nom_fr`, so a typo
  // here would ship two published artefacts that disagree about the same name.
  if (override !== nomEn) {
    failures.push(
      `[A18] ${label}: ${OVERRIDES_REL} maps "${key}" to "${override}", but ` +
        `nom_en in ${SOURCE_REL} is "${nomEn}"`,
    );
  }
}

/* =========================================================================== *
 * Phase 6 — emit the five generated TypeScript files
 *
 * Deterministic: document order, no sorting, no Object.keys iteration over a
 * map, NO TIMESTAMPS. Running the build twice with no source change must
 * produce a zero-byte diff, so PR diffs on these files stay reviewable.
 *
 * One record per line, on purpose: a changed record is then exactly one changed
 * line in review. These files are excluded from prettier and eslint, so they are
 * emitted already-tidy (2-space indent, double quotes, semicolons) rather than
 * formatted afterwards.
 * =========================================================================== */

/** A TypeScript double-quoted string literal. JSON escaping is a subset. */
function tsString(value: string): string {
  return JSON.stringify(value);
}

function tsName(name: LocalizedName): string {
  return `{ ar: ${tsString(name.ar)}, fr: ${tsString(name.fr)}, en: ${tsString(name.en)} }`;
}

function chunk<T>(items: readonly T[], size: number): T[][] {
  const rows: T[][] = [];
  for (let index = 0; index < items.length; index += size) {
    rows.push(items.slice(index, index + size));
  }
  return rows;
}

function emitCodes(model: Model): string {
  const codes = model.wilayas.map((wilaya) => wilaya.code);
  const unionRows = chunk(codes, 10).map((row) => `  | ${row.join(" | ")}`);
  const listRows = chunk(codes, 10).map((row) => `  ${row.join(", ")},`);
  return [
    BANNER,
    "//",
    "// Both the union and the list are derived from data/algeria.json. A hand-written",
    "// 69-member union rots the moment a reform adds a wilaya; a generated one cannot",
    "// drift from the data.",
    "",
    "/**",
    " * An official Algerian wilaya code, 1..69 (Loi 26-06).",
    " *",
    ' * This is the *number*, not the zero-padded string: `1`, not `"01"`. The padded',
    " * form is derived in the accessor layer.",
    " */",
    "export type WilayaCode =",
    ...unionRows.slice(0, -1),
    `${unionRows.slice(-1).join("")};`,
    "",
    "/** Every wilaya code, in document order. */",
    "export const WILAYA_CODES = [",
    ...listRows,
    "] as const;",
    "",
  ].join("\n");
}

