/**
 * scripts/build-data.ts — the one generator for every derived artefact in this repo.
 *
 * Run from the repo root:
 *
 *   pnpm build:data              regenerate everything (77 outputs)
 *   pnpm build:data -- --check   verify the tree is up to date, write nothing
 *
 * Inputs (read-only):
 *   data/algeria.json            the hand-edited source of truth (nested tree)
 *   data/raw/en-overrides.json   the auditable English exonym table (1 entry today)
 *
 * Outputs:
 *   data/wilayas.json                      \
 *   data/dairas.json                        |  the frozen public JSON contract,
 *   data/communes.json                      |  regenerated BYTE-IDENTICALLY
 *   data/by-wilaya/01.json .. 69.json      /
 *   packages/js/src/generated/{codes,meta,wilayas,dairas,communes,search-keys}.ts
 *
 * Zero npm dependencies — Node built-ins only. This is a dev script, so
 * `node:fs` is fine here; the shipped library is what must stay fs-free.
 *
 * Six phases, in this order:
 *   1  read and type the source                       readSource / readOverrides
 *   2  assert integrity (19 checks, all accumulated)  assertIntegrity
 *   3  project the four JSON shapes                   projectJsonOutputs
 *   4  write (or --check) all 77 outputs              writeOutputs / checkOutputs
 *   5  slug ids + English resolution                  slug / buildModel
 *   6  emit the five generated TypeScript files       emitTypeScriptOutputs
 *
 * Phase 5 is *declared* below phases 1–4 but *runs* before phase 2: assertion 19
 * (unique ids) and assertions 17/18 (the override table) are checks on the ids
 * phase 5 mints, so the model has to exist before the gate can run. Function
 * declarations hoist, so `main()` is free to call them in dependency order.
 */

