    "",
    "/**",
    " * Provenance and size constants for the bundled dataset.",
    " *",
    " * Provenance is EXPORTED, not merely documented: users of an administrative",
    " * dataset get asked by compliance, legal and procurement teams to prove where",
    " * the boundaries came from and as of when. A constant they can log, print in a",
    " * report or assert on in a test answers that in one line.",
